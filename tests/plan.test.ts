import { describe, it, expect } from 'vitest';
import { isInvalidDate, loadOrder, migrationScript, parseOnInvalid, parseOracleType, planTables, PlanConflict } from '../src/plan/model';
import { NormSchema } from '../src/schema/types';
import seed from './fixtures/seed-schema.json';

const source = seed.source as NormSchema;
const target = seed.target as NormSchema;

/** Plano como o Core entrega depois da homologacao (seed). */
const plan: PlanConflict[] = [
  { id: 'clientes.email', table: 'clientes', column: 'email', decidedBy: 'ai', status: 'RESOLVED', resolution: 'Usar VARCHAR2(300 CHAR)' },
  { id: 'clientes.ativo', table: 'clientes', column: 'ativo', decidedBy: 'human', status: 'RESOLVED', resolution: 'Manter NUMBER(1); o valor 2 significa bloqueado' },
  { id: 'pedidos.criado_em', table: 'pedidos', column: 'criado_em', decidedBy: 'human', status: 'RESOLVED', resolution: 'Converter para NULL e registrar no relatorio' },
  { id: 'clientes.id', table: 'clientes', column: 'id', decidedBy: 'rule', status: 'RESOLVED', resolution: 'Mapear INT -> NUMBER(10)' },
];

describe('parseOracleType: texto livre vira tipo reconstruido, nunca copiado', () => {
  it('reconhece os tipos usuais', () => {
    expect(parseOracleType('Usar VARCHAR2(300 CHAR)')?.type).toBe('VARCHAR2(300 CHAR)');
    expect(parseOracleType('varchar2( 200 )')?.type).toBe('VARCHAR2(200)');
    expect(parseOracleType('NUMBER(18, 4)')).toMatchObject({ type: 'NUMBER(18,4)', precision: 18, scale: 4 });
    expect(parseOracleType('ampliar para CLOB')?.type).toBe('CLOB');
    expect(parseOracleType('TIMESTAMP')?.type).toBe('TIMESTAMP(6)');
    expect(parseOracleType('nao sei')).toBeNull();
  });

  it('nao deixa texto da IA/humano entrar no DDL', () => {
    const t = parseOracleType('VARCHAR2(300) ); DROP TABLE CLIENTES; --');
    expect(t?.type).toBe('VARCHAR2(300)');
  });
});

describe('decisao sobre valores invalidos', () => {
  it('NULL, data padrao ou nada', () => {
    expect(parseOnInvalid('Converter para NULL')).toEqual({ kind: 'null' });
    expect(parseOnInvalid('manter NOT NULL e usar 1970-01-01')).toEqual({ kind: 'default', value: '1970-01-01' });
    expect(parseOnInvalid('manter NOT NULL')).toBeNull();
    expect(isInvalidDate('0000-00-00 00:00:00')).toBe(true);
    expect(isInvalidDate('2024-00-15')).toBe(true);
    expect(isInvalidDate('2024-03-11 10:00:00')).toBe(false);
  });
});

describe('planTables + script (seed)', () => {
  const tables = loadOrder(planTables(source, target, plan));

  it('aplica so o que foi decidido por IA/humano; regra mantem o destino declarado', () => {
    const clientes = tables.find((t) => t.name === 'clientes')!;
    const email = clientes.columns.find((c) => c.name === 'email')!;
    expect(email).toMatchObject({ type: 'VARCHAR2(300 CHAR)', changedFrom: 'VARCHAR2(200)' });
    expect(clientes.columns.find((c) => c.name === 'id')!.changedFrom).toBeNull();
    expect(clientes.columns.find((c) => c.name === 'ativo')!.changedFrom).toBeNull(); // NUMBER(1) = o declarado
  });

  it('pais antes dos filhos', () => {
    const order = tables.map((t) => t.name);
    expect(order.indexOf('clientes')).toBeLessThan(order.indexOf('pedidos'));
    expect(order.indexOf('pedidos')).toBeLessThan(order.indexOf('eventos'));
  });

  it('script: ALTER do e-mail, NULL decidido para data invalida, IDENTITY e trigger sugerida', () => {
    const { script, statements } = migrationScript('VENDAS', tables, new Map([['pedidos.criado_em', 2]]), { generatedAt: 't' });
    expect(script).toContain('ALTER TABLE "VENDAS"."CLIENTES" MODIFY ("EMAIL" VARCHAR2(300 CHAR));');
    expect(script).toContain('ALTER TABLE "VENDAS"."PEDIDOS" MODIFY ("CRIADO_EM" NULL);');
    expect(script).toContain('GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)');
    expect(script).toContain('-- CREATE OR REPLACE TRIGGER');
    expect(statements).toBe(2 + 3); // 2 alteracoes + 3 IDENTITY
  });
});
