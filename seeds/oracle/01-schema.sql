-- ---------------------------------------------------------------------------
-- Banco de DESTINO (Oracle Database Free 23ai) — schema VENDAS
--
-- Este e o schema de destino DECLARADO, propositalmente imperfeito: e ele que
-- torna os conflitos visiveis quando comparado a origem.
--
-- O caso central: EMAIL foi declarado VARCHAR2(200 CHAR), menor do que os dados
-- reais exigem. Aplicar a migracao sem analise truncaria 2 registros em
-- silencio — exatamente o failure mode que a plataforma existe para impedir.
--
-- Executado pelo container gvenzl/oracle-free como o usuario da aplicacao.
-- ---------------------------------------------------------------------------

CREATE TABLE CLIENTES (
  ID             NUMBER(10)          GENERATED BY DEFAULT AS IDENTITY,
  NOME           VARCHAR2(120 CHAR)  NOT NULL,
  EMAIL          VARCHAR2(200 CHAR)  NOT NULL,
  CPF            CHAR(11)            NULL,
  ATIVO          NUMBER(1)           DEFAULT 1 NOT NULL,
  SALDO          NUMBER(18,4)        DEFAULT 0 NOT NULL,
  CRIADO_EM      TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  ATUALIZADO_EM  TIMESTAMP           DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CLIENTES PRIMARY KEY (ID),
  CONSTRAINT UK_CLIENTES_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE PEDIDOS (
  ID          NUMBER(10)         GENERATED BY DEFAULT AS IDENTITY,
  CLIENTE_ID  NUMBER(10)         NOT NULL,
  -- Oracle nao possui ENUM: o equivalente e VARCHAR2 com CHECK.
  STATUS      VARCHAR2(20 CHAR)  DEFAULT 'novo' NOT NULL,
  TOTAL       NUMBER(18,4)       NOT NULL,
  OBSERVACAO  CLOB               NULL,
  CRIADO_EM   TIMESTAMP          NOT NULL,
  CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
  CONSTRAINT FK_PEDIDOS_CLIENTE FOREIGN KEY (CLIENTE_ID)
    REFERENCES CLIENTES (ID),
  CONSTRAINT CK_PEDIDOS_STATUS CHECK
    (STATUS IN ('novo', 'pago', 'enviado', 'cancelado'))
);

CREATE TABLE EVENTOS (
  ID           NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
  PEDIDO_ID    NUMBER(10)         NOT NULL,
  TIPO         VARCHAR2(60 CHAR)  NOT NULL,
  DADOS        CLOB               NULL,
  VALOR        BINARY_DOUBLE      NULL,
  OCORRIDO_EM  TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_EVENTOS PRIMARY KEY (ID),
  CONSTRAINT FK_EVENTOS_PEDIDO FOREIGN KEY (PEDIDO_ID)
    REFERENCES PEDIDOS (ID)
);

-- O destino nasce vazio: a carga e o resultado da migracao, nao do seed.
